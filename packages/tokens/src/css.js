// Renders the tokens as CSS variables (--bnb-*). Light is the base; dark applies with
// data-theme="dark" (Vue apps, plain pages), data-mantine-color-scheme="dark" (Mantine apps),
// or the system setting when the page chose neither.
import { accentTextOn, textOn } from './contrast.js'
import tokens from './tokens.js'

/** @param {Record<string, string | number>} vars @param {string} indent */
const block = (vars, indent = '  ') =>
  Object.entries(vars)
    .map(([k, v]) => `${indent}${k}: ${v};`)
    .join('\n')

/** @param {'light' | 'dark'} scheme */
function schemeVars(scheme) {
  const n = tokens.neutrals[scheme]
  const s = tokens.status[scheme]
  const sh = tokens.shadow[scheme]
  /** @type {Record<string, string>} */
  const vars = { 'color-scheme': scheme }
  for (const [k, v] of Object.entries(n)) vars[`--bnb-${k}`] = v
  for (const [k, v] of Object.entries(s)) {
    vars[`--bnb-${k}`] = v
    vars[`--bnb-${k}-soft`] = `color-mix(in srgb, var(--bnb-${k}) 14%, transparent)`
  }
  vars['--bnb-accent'] = `var(--bnb-accent-${scheme})`
  vars['--bnb-on-accent'] = `var(--bnb-on-accent-${scheme})`
  vars['--bnb-accent-hover'] = `color-mix(in srgb, var(--bnb-accent), ${scheme === 'light' ? 'black' : 'white'} 12%)`
  vars['--bnb-accent-soft'] = 'color-mix(in srgb, var(--bnb-accent) 14%, transparent)'
  // The accent as text and links, readable on every neutral (accentCss and the ui theme set it per
  // theme). An app that sets only its accent falls back to the accent itself.
  vars['--bnb-accent-text'] = `var(--bnb-accent-text-${scheme}, var(--bnb-accent))`
  // Text on a filled status colour (a "Failed" badge, a delete button).
  vars['--bnb-on-status'] = scheme === 'light' ? '#ffffff' : '#0f0f11'
  for (const [k, v] of Object.entries(sh)) vars[`--bnb-shadow-${k}`] = v
  vars['--bnb-dot'] = tokens.dotGrid[scheme]
  vars['--bnb-focus-ring'] = '0 0 0 2px var(--bnb-bg), 0 0 0 4px color-mix(in srgb, var(--bnb-accent) 70%, transparent)'
  return vars
}

/** Variables that are the same in both themes. */
function sharedVars() {
  /** @type {Record<string, string>} */
  const vars = {
    '--bnb-accent-light': tokens.defaultAccent.light,
    '--bnb-accent-dark': tokens.defaultAccent.dark,
    '--bnb-on-accent-light': textOn(tokens.defaultAccent.light),
    '--bnb-on-accent-dark': textOn(tokens.defaultAccent.dark),
    '--bnb-accent-text-light': accentTextOn(tokens.defaultAccent.light, tokens.neutrals.light),
    '--bnb-accent-text-dark': accentTextOn(tokens.defaultAccent.dark, tokens.neutrals.dark),
    '--bnb-text': '1',
  }
  for (const [k, v] of Object.entries(tokens.space)) vars[`--bnb-space-${k}`] = v
  for (const [k, v] of Object.entries(tokens.radius)) vars[`--bnb-radius-${k}`] = v
  vars['--bnb-font-sans'] = tokens.font.sans
  vars['--bnb-font-mono'] = tokens.font.mono
  for (const [k, v] of Object.entries(tokens.fontSize)) vars[`--bnb-fs-${k}`] = `calc(${v}px * var(--bnb-text))`
  vars['--bnb-lh-tight'] = String(tokens.lineHeight.tight)
  vars['--bnb-lh-normal'] = String(tokens.lineHeight.normal)
  vars['--bnb-dot-size'] = tokens.dotGrid.size
  vars['--bnb-dot-grid'] = `radial-gradient(circle at ${tokens.dotGrid.dot} ${tokens.dotGrid.dot}, var(--bnb-dot) ${tokens.dotGrid.dot}, transparent 0)`
  return vars
}

const DARK = ':root[data-theme="dark"], :root[data-mantine-color-scheme="dark"], [data-theme="dark"]'
const SYSTEM_DARK = ':root:not([data-theme="light"]):not([data-mantine-color-scheme="light"])'

/** The whole stylesheet. */
export function renderCss() {
  const dark = block(schemeVars('dark'))
  return `/* @bitsandbricks/tokens: generated by scripts/build.mjs from src/tokens.js. Do not edit. */
:root {
${block(sharedVars())}
${block(schemeVars('light'))}
}

${DARK} {
${dark}
}

@media (prefers-color-scheme: dark) {
  ${SYSTEM_DARK} {
${block(schemeVars('dark'), '    ')}
  }
}

/* The dot grid behind a page's content. */
.bnb-dot-grid {
  background-color: var(--bnb-bg);
  background-image: var(--bnb-dot-grid);
  background-size: var(--bnb-dot-size) var(--bnb-dot-size);
}
`
}

/**
 * The CSS an app adds to set its own accent: `accentCss({ light: '#b85a0a', dark: '#f59a23' })`.
 * Text on the fill is worked out per theme. @param {{ light: string, dark: string }} accent @param {string} [selector]
 */
export function accentCss(accent, selector = ':root') {
  return `${selector} {
  --bnb-accent-light: ${accent.light};
  --bnb-accent-dark: ${accent.dark};
  --bnb-on-accent-light: ${textOn(accent.light)};
  --bnb-on-accent-dark: ${textOn(accent.dark)};
  --bnb-accent-text-light: ${accentTextOn(accent.light, tokens.neutrals.light)};
  --bnb-accent-text-dark: ${accentTextOn(accent.dark, tokens.neutrals.dark)};
}
`
}
