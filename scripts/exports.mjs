// Writes packages/ui/src/exports.gen.ts: one `export *` line for every module in src/, so adding a
// component or hook never touches a shared line in index.ts. The file is not committed; install,
// lint, typecheck, test, build and Storybook write it first. Everything a module exports is public:
// keep helpers unexported, or in a `*.texts.ts`, test or story file, which are left out.
// A folder with its own index.ts is a subpath entry (src/dates -> @bitsandbricks/ui/dates) and is
// left out too, so its optional peer dependencies (@mantine/dates, dayjs) stay optional.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const PACKAGES = ['ui']
const SKIP = /(\.test|\.stories|\.texts|\.gen|\.d)\.tsx?$/
const root = join(import.meta.dirname, '..')

function modules(src, dir = src) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) {
      const subpathEntry = existsSync(join(path, 'index.ts')) || existsSync(join(path, 'index.tsx'))
      return entry.name === 'test' || subpathEntry ? [] : modules(src, path)
    }
    if (!/\.tsx?$/.test(entry.name) || SKIP.test(entry.name)) return []
    const spec = `./${relative(src, path).replace(/\\/g, '/').replace(/\.tsx?$/, '')}`
    return spec === './index' ? [] : [spec]
  })
}

// A package's other entries (exports "./spotlight": dist/spotlight.js) are left out of the main one,
// with their folder (src/spotlight/): they may need an optional peer the main entry must not import.
function otherEntries(dir) {
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  return Object.entries(pkg.exports ?? {}).flatMap(([key, value]) => {
    const target = typeof value === 'string' ? value : value?.default
    const m = key !== '.' && /^\.\/dist\/(.+)\.js$/.exec(target ?? '')
    return m ? [`./${m[1]}`] : []
  })
}

for (const name of PACKAGES) {
  const src = join(root, 'packages', name, 'src')
  const skip = otherEntries(join(root, 'packages', name))
  const file = join(src, 'exports.gen.ts')
  const lines = modules(src).filter((spec) => !skip.some((e) => spec === e || spec.startsWith(`${e}/`))).sort((a, b) => a.localeCompare(b, 'en')).map((spec) => `export * from '${spec}'`)
  const text = `// Generated by scripts/exports.mjs from the files in src/. Do not edit; not committed.\n${lines.join('\n')}\n`
  let old = ''
  try { old = readFileSync(file, 'utf8') } catch { /* first run */ }
  if (old !== text) writeFileSync(file, text)
}
